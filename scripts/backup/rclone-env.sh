#!/usr/bin/env bash
# rclone "remotes" from environment variables (nothing written to disk).
#   b2:    the Backblaze vault
#   supa:  Supabase Storage (its S3-compatible endpoint)
export RCLONE_CONFIG_B2_TYPE="${RCLONE_CONFIG_B2_TYPE:-b2}"
export RCLONE_CONFIG_B2_ACCOUNT="${RCLONE_CONFIG_B2_ACCOUNT:-${B2_KEY_ID:-}}"
export RCLONE_CONFIG_B2_KEY="${RCLONE_CONFIG_B2_KEY:-${B2_APP_KEY:-}}"
export RCLONE_CONFIG_SUPA_TYPE="${RCLONE_CONFIG_SUPA_TYPE:-s3}"
export RCLONE_CONFIG_SUPA_PROVIDER="${RCLONE_CONFIG_SUPA_PROVIDER:-Other}"
export RCLONE_CONFIG_SUPA_ENDPOINT="${RCLONE_CONFIG_SUPA_ENDPOINT:-${SUPABASE_S3_ENDPOINT:-}}"
export RCLONE_CONFIG_SUPA_REGION="${RCLONE_CONFIG_SUPA_REGION:-${SUPABASE_S3_REGION:-us-east-2}}"
export RCLONE_CONFIG_SUPA_ACCESS_KEY_ID="${RCLONE_CONFIG_SUPA_ACCESS_KEY_ID:-${SUPABASE_S3_KEY_ID:-}}"
export RCLONE_CONFIG_SUPA_SECRET_ACCESS_KEY="${RCLONE_CONFIG_SUPA_SECRET_ACCESS_KEY:-${SUPABASE_S3_SECRET:-}}"
export RCLONE_CONFIG_SUPA_FORCE_PATH_STYLE="${RCLONE_CONFIG_SUPA_FORCE_PATH_STYLE:-true}"
